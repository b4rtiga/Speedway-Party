glyphs = []
for code in range(32, 96):
    glyphs.append((chr(code), rows_to_bytes(NONE, G.get(chr(code), G[' ']), (NONE, NONE))))
for base, acc, og, shape in POLISH:
    glyphs.append((base + "'", rows_to_bytes(acc, shape or G[base], OGONEK if og else (NONE, NONE))))
for ch in "abcdefghijklmnopqrstuvwxyz":                 # glify 73..98
    body, tail = LOWER[ch]
    glyphs.append((ch, rows_to_bytes(NONE, body, tail or (NONE, NONE))))
# (c) na 7 kolumnach (komorka ma 8): w 5 px kolko zlewa sie z litera C i wyglada jak "@"
glyphs.append(("(c)", rows_to_bytes(".......", "..###..|.#...#.|#..##.#|#.#...#|#..##.#|.#...#.|..###..",
                                    (".......", "......."))))   # 99

def main():
    lines = ["/* font.c - WYGENEROWANE przez tools/genfont.py, nie edytowac recznie. */",
             '#include "text.h"', "",
             "const UBYTE g_font[FONT_GLYPHS][FONT_H] = {"]
    for name, data in glyphs:
        lines.append("    {" + ",".join("0x%02X" % b for b in data) + "},  /* " + name.replace('*/', '* /') + " */")
    lines.append("};")
    out = pathlib.Path(__file__).resolve().parent.parent / "src" / "font.c"
    out.write_text("\n".join(lines) + "\n", encoding="ascii", errors="replace")
    print("zapisano", out, len(glyphs), "znakow")


if __name__ == "__main__":
    main()
