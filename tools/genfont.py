ACUTE, DOT, NONE = "...#.", "..#..", "....."
OGONEK = ("...#.", "....#")
# (bazowa litera, akcent w wierszu 0, ogonek, zamiennik ksztaltu)
POLISH = [
 ('A', NONE, True, None),  ('C', ACUTE, False, None), ('E', NONE, True, None),
 ('L', NONE, False, "#....|#....|#.#..|##...|#....|#....|#####"),
 ('N', ACUTE, False, None), ('O', ACUTE, False, None), ('S', ACUTE, False, None),
 ('Z', ACUTE, False, None), ('Z', DOT, False, None),
]

def rows_to_bytes(top, body, tail):
    rows = [top] + body.split('|') + list(tail)
    out = []
    for r in rows:
        b = 0
        for i, ch in enumerate(r):
            if ch == '#':
                b |= 0x40 >> i          # kolumny 1..5 komorki 8 px
        out.append(b)
    return out

